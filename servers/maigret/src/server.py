def check_username(value) -> str:
    if not isinstance(value, str) or not _USERNAME.match(value.strip()):
        raise Refused("username: letters, digits, '_', '.' and '-' (at most 64, starting with a letter or digit), "
                      "e.g. john_doe")
    return value.strip()


def _int(value, name: str, low: int, high: int) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or not low <= value <= high:
        raise Refused(f"{name}: a whole number from {low} to {high}")
    return value


def _text(value, name: str, limit: int, example: str) -> str:
    if not isinstance(value, str) or len(value) > limit or _CONTROLS.search(value):
        raise Refused(f"{name}: text of at most {limit} characters on one line, e.g. {example}")
    return value.strip()


def check_tags(value) -> list[str]:
    text = _text(value, "tags", 300, "coding,gaming")
    tags = [t.strip().lower() for t in text.split(",") if t.strip()]
    known = set(database().tags)
    unknown = [t for t in tags if t not in known]
    if unknown:
        raise Refused(f"tags: unknown {', '.join(shown(t, 40) for t in unknown[:5])}; list_tags shows the tags")
    return tags


# --- one check -------------------------------------------------------------------------------------------------------

class Verdict:
    def __init__(self, site: Site, status: str, url: str = "", detail: str = "", http_status: int | None = None):
        self.site, self.status, self.url, self.detail, self.http_status = site, status, url, detail, http_status


def public_address(address: str) -> bool:
    ip = ipaddress.ip_address(address.split("%", 1)[0])
    if ip.version == 6 and ip.ipv4_mapped:
        ip = ip.ipv4_mapped
    return ip.is_global and not ip.is_multicast


async def check_host(url: str) -> str | None:
    """Why URL's host is not reached ('refused: ...'), or None: http(s) only, every address of the host public."""
    parts = urllib.parse.urlsplit(url)
    if parts.scheme not in ("http", "https") or not parts.hostname:
        return f"refused: {shown(url, 120)} is not an http(s) address"
    host = parts.hostname
    try:
        ipaddress.ip_address(host)
        return f"refused: {host} is an IP address, not a site's name"
    except ValueError:
        pass
    if host.endswith((".onion", ".i2p", ".local", ".localhost", ".internal")) or host == "localhost":
        return f"refused: {host} is not a public name"
    try:
        addresses = await resolve(host, parts.port or (443 if parts.scheme == "https" else 80))
    except (socket.gaierror, UnicodeError) as exc:
        return f"name lookup failed ({shown(getattr(exc, 'strerror', None) or exc, 80)})"
    if not addresses or not all(public_address(address) for address in addresses):
        return f"refused: {host} resolves to a non-public address"
    return None


async def resolve(host: str, port: int) -> list[str]:
    """The addresses HOST has (the system's resolver: behind sandbox-ai's Tor profile, Tor's)."""
    infos = await asyncio.get_running_loop().getaddrinfo(host, port, type=socket.SOCK_STREAM)
    return [info[4][0] for info in infos]


def error_page(site: Site, text: str, status: int) -> str | None:
    """maigret 0.6.6 error_detection.detect_error_page: why the answer is no evidence either way, or None."""
    if text:
        for flag, message in site.errors.items():
            if flag and flag in text:
                return f"Site-specific: {message}"
        for flag, message in COMMON_ERRORS.items():
            if flag in text:
                return message
    if status == 403 and not site.ignore403:
        return "Access denied: 403 status code"
    if status == 401:
        return "Login required: 401 status code"
    if status == 429:
        return "Rate limited: 429 status code"
    if status == 999:
        return "Access denied: 999 status code"
    if status >= 500:
        return f"Server: {status} status code"
    return None


def judge(site: Site, username: str, text: str, status: int) -> tuple[str, str]:
    """maigret 0.6.6 checking.process_site_result: ('found' | 'not found', why) for an answer without an error."""
    if text:
        if not site.presence:
            present = True
            if any(ord(c) > 127 for c in username) and username not in text:
                present = False
        else:
            present = any(flag in text for flag in site.presence)
    else:
        present = False
    if site.check_type == "message":
        absent = [flag for flag in site.absence if flag in text]
        if absent:
            return "not found", f"the page says {shown(absent[0], 60)!r}"
        if present:
            return "found", "the page has the profile's marks" if site.presence else "the page exists"
        return "not found", "the page lacks the profile's marks"
    if site.check_type == "status_code":
        return ("found", f"HTTP {status}") if 200 <= status < 300 else ("not found", f"HTTP {status}")
    # response_url: redirects are not followed; a 2xx with the presence marks is the profile
    if 200 <= status < 300 and present:
        return "found", f"HTTP {status} without a redirect"
    return "not found", f"HTTP {status}" + (" (a redirect)" if 300 <= status < 400 else "")


async def fetch(client: httpx.AsyncClient, site: Site, username: str) -> Verdict:
    url = site.profile_url(username)
    probe = site.probe_url(username)
    if not site.accepts(username):
        return Verdict(site, "skipped", url, "the site does not allow such a username")
    method = site.method or ("head" if site.check_type == "status_code" and site.head_only else "get")
    headers = {"User-Agent": USER_AGENT}
    headers.update({k: v for k, v in site.headers.items() if k.lower() not in OWN_HEADERS})
    body = None
    if site.payload and method == "post":
        payload = {k: (v.format(username=username) if isinstance(v, str) else v) for k, v in site.payload.items()}
        if headers.get("Content-Type") == "application/x-www-form-urlencoded":
            body = {"data": payload}
        else:
            body = {"json": payload}
    follow = site.check_type != "response_url"
    target = probe
    for _ in range(MAX_REDIRECTS + 1):
        problem = await check_host(target)
        if problem:
            return Verdict(site, "error", url, problem)
        request = client.build_request(method.upper(), target, headers=headers, **(body or {}))
        response = await client.send(request, stream=True)
        try:
            if follow and response.is_redirect and response.headers.get("location"):
                target = str(response.url.join(response.headers["location"]))
                if response.status_code in (301, 302, 303) and method == "post":
                    method, body = "get", None
                continue
            raw = bytearray()
            if method != "head":
                # decoded (gzip, deflate, brotli if installed) chunk by chunk: the bound holds for what is unpacked
                async for chunk in response.aiter_bytes():
                    raw += chunk
                    if len(raw) >= MAX_BODY:
                        break
            raw = bytes(raw[:MAX_BODY])
            charset = site.encoding or response.charset_encoding or "utf-8"
            try:
                text = raw.decode(charset, "ignore")
            except LookupError:
                text = raw.decode("utf-8", "ignore")
            status = response.status_code
        finally:
            await response.aclose()
        error = error_page(site, text, status)
        if error:
            return Verdict(site, "error", url, error, status)
        verdict, why = judge(site, username, text, status)
        return Verdict(site, verdict, url, why, status)
    return Verdict(site, "error", url, f"more than {MAX_REDIRECTS} redirects")


async def check(client: httpx.AsyncClient, site: Site, username: str) -> Verdict:
    try:
        return await asyncio.wait_for(fetch(client, site, username), SITE_SECONDS)
    except asyncio.TimeoutError:
        return Verdict(site, "error", site.profile_url(username), f"no answer within {SITE_SECONDS:g} s")
    except httpx.TooManyRedirects:
        return Verdict(site, "error", site.profile_url(username), "too many redirects")
    except httpx.HTTPError as exc:
        kind = type(exc).__name__
        reason = {"ConnectError": "could not connect", "ConnectTimeout": "connecting timed out",
                  "ReadTimeout": "the answer stalled", "RemoteProtocolError": "the site broke off the answer",
                  "ProxyError": "the proxy refused"}.get(kind, kind)
        return Verdict(site, "error", site.profile_url(username), reason)
    except (ValueError, KeyError, IndexError) as exc:  # a URL or payload template of the entry that does not format
        return Verdict(site, "error", "", f"the entry cannot be used ({type(exc).__name__})")


def client() -> httpx.AsyncClient:
    # trust_env: sandbox-ai's allowlist proxy (HTTPS_PROXY) when it sets one; certificates always verified
    return httpx.AsyncClient(timeout=httpx.Timeout(SITE_SECONDS, connect=6.0), follow_redirects=False,
                             limits=httpx.Limits(max_connections=CONCURRENCY, max_keepalive_connections=8),
                             trust_env=True, verify=True)


async def check_many(sites: list[Site], username: str) -> tuple[list[Verdict], list[Site]]:
    """(verdicts, sites not checked in time): at most CONCURRENCY at a time, all within CALL_SECONDS."""
    semaphore = asyncio.Semaphore(CONCURRENCY)
    deadline = time.monotonic() + CALL_SECONDS

    async with client() as http:
        async def one(site: Site) -> Verdict | None:
            async with semaphore:
                if time.monotonic() + 1 > deadline:
                    return None
                left = deadline - time.monotonic()
                try:
                    return await asyncio.wait_for(check(http, site, username), max(1.0, left))
                except asyncio.TimeoutError:
                    return None
        results = await asyncio.gather(*(one(site) for site in sites))
    verdicts = [r for r in results if r is not None]
    late = [site for site, r in zip(sites, results) if r is None]
    return verdicts, late


# --- answers ---------------------------------------------------------------------------------------------------------

def bounded(lines: list[str]) -> str:
    out: list[str] = []
    used = 0
    for index, line in enumerate(lines):
        if used + len(line) + 1 > MAX_CHARS - 200:
            out.append(f"... ({len(lines) - index} more lines cut to stay within {MAX_CHARS:,} characters)")
            break
        out.append(line)
        used += len(line) + 1
    return "\n".join(out)


def answer(work) -> str:
    try:
        return work()
    except Refused as exc:
        raise ToolError(str(exc)) from None
    except Exception as exc:  # noqa: BLE001 - reported by type, not hidden
        log.error("unexpected %s", type(exc).__name__)
        raise ToolError(f"internal error ({type(exc).__name__})") from None


async def answer_async(work) -> str:
    try:
        return await work()
    except Refused as exc:
        raise ToolError(str(exc)) from None
    except Exception as exc:  # noqa: BLE001
        log.error("unexpected %s", type(exc).__name__)
        raise ToolError(f"internal error ({type(exc).__name__})") from None


