class Site:
    """One entry of data.json with its engine's template applied (maigret's MaigretSite.update_from_engine)."""

    def __init__(self, name: str, entry: dict, engines: dict, index: int):
        data = dict(entry)
        engine = entry.get("engine")
        if isinstance(engine, str) and engine in engines:
            for key, value in (engines[engine].get("site") or {}).items():
                if isinstance(value, dict):
                    merged = dict(data.get(key) or {})
                    merged.update(value)          # the engine's entries win, as in maigret
                    data[key] = merged
                elif isinstance(value, list):
                    data[key] = list(data.get(key) or []) + value
                elif key not in entry:            # a value the entry states itself wins
                    data[key] = value
        self.name = name
        self.index = index
        self.url = str(data.get("url") or "")
        self.url_main = str(data.get("urlMain") or "")
        self.url_subpath = str(data.get("urlSubpath") or "")
        self.url_probe = data.get("urlProbe")
        self.check_type = str(data.get("checkType") or "")
        self.presence = [str(s) for s in data.get("presenseStrs") or []]
        self.absence = [str(s) for s in data.get("absenceStrs") or []]
        self.errors = {str(k): str(v) for k, v in (data.get("errors") or {}).items()}
        self.ignore403 = bool(data.get("ignore403"))
        self.regex = data.get("regexCheck")
        self.headers = {str(k): str(v) for k, v in (data.get("headers") or {}).items()}
        self.method = str(data.get("requestMethod") or "").lower()
        self.payload = data.get("requestPayload") or None
        self.head_only = bool(data.get("requestHeadOnly"))
        self.encoding = data.get("encoding")
        self.tags = [str(t) for t in data.get("tags") or []]
        rank = data.get("alexaRank")
        self.rank = rank if isinstance(rank, int) and rank > 0 else sys.maxsize
        self.similar = bool(data.get("similarSearch"))
        self.source = data.get("source")
        self.why_not = self._why_not(data)

    def _why_not(self, data: dict) -> str:
        """Why this server does not check the entry ('' when it does)."""
        if data.get("disabled"):
            return "disabled in maigret's database"
        if data.get("type", "username") != "username":
            return f"takes a {data['type']}, not a username"
        if data.get("protocol"):
            return f"a {data['protocol']} entry"
        if data.get("activation"):
            return "needs maigret's activation (tokens fetched from the site)"
        if {h.lower() for h in self.headers} & SENSITIVE_HEADERS:
            return "its request carries a cookie or token of the site"
        blocking = sorted(BLOCKING_PROTECTIONS & set(data.get("protection") or []))
        if blocking:
            return f"behind a bot protection a plain client cannot pass ({', '.join(blocking)})"
        if self.check_type not in ("status_code", "message", "response_url") or not self.url:
            return "an incomplete entry"
        if self.method not in ("", "get", "post", "head"):
            return "an unknown request method"
        return ""

    def profile_url(self, username: str) -> str:
        return self._format(self.url, username)

    def probe_url(self, username: str) -> str:
        return self._format(self.url_probe, username) if self.url_probe else self.profile_url(username)

    def _format(self, template: str, username: str) -> str:
        url = str(template).format(urlMain=self.url_main, urlSubpath=self.url_subpath,
                                   username=urllib.parse.quote(username, safe=""))
        return re.sub(r"(?<!:)/+", "/", url)

    def accepts(self, username: str) -> bool:
        if not self.regex:
            return True
        try:
            return re.search(str(self.regex), username) is not None
        except re.error:
            return False


class Database:
    def __init__(self, path: str):
        with open(path, encoding="utf-8") as handle:
            raw = json.load(handle)
        engines = raw.get("engines") or {}
        self.sites = [Site(name, entry, engines, index) for index, (name, entry) in enumerate(raw["sites"].items())]
        self.by_name = {site.name.lower(): site for site in self.sites}
        self.tags = sorted({tag for site in self.sites for tag in site.tags})

    def checkable(self, tags: list[str]) -> list[Site]:
        """The sites this server checks, most popular first (maigret's alexaRank; unranked ones after, in file
        order), with one of TAGS when given."""
        wanted = set(tags)
        found = [s for s in self.sites if not s.why_not and (not wanted or wanted & {t.lower() for t in s.tags})]
        return sorted(found, key=lambda s: (s.rank, s.index))


_DB: Database | None = None


def database() -> Database:
    global _DB
    if _DB is None:
        _DB = Database(DATA)
    return _DB


