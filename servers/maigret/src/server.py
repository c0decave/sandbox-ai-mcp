@mcp.tool(annotations=SEARCH, structured_output=False)
async def search_username(username: str, limit: int = DEFAULT_SITES, offset: int = 0, tags: str = "") -> str:
    """Check a username on many sites, the most popular first, and list the accounts found (with their URLs).
    One call checks LIMIT sites within 45 s; the answer says which offset checks the next ones.

    Args:
        username: the name to look for, e.g. "john_doe"
        limit: sites to check in this call (default 100, at most 200)
        offset: skip this many of the ranked sites (the last answer names the next offset)
        tags: only sites with one of these tags, comma-separated, e.g. "coding,gaming" or "de" (list_tags)
    """
    async def work() -> str:
        name = check_username(username)
        count = _int(limit, "limit", 1, MAX_SITES)
        start = _int(offset, "offset", 0, 100_000)
        wanted = check_tags(tags)
        ranked = database().checkable(wanted)
        if start >= len(ranked) and ranked:
            raise Refused(f"offset: there are {len(ranked)} sites to check" + (f" with tags {tags}" if wanted else ""))
        batch = ranked[start:start + count]
        verdicts, late = await check_many(batch, name)
        found = sorted((v for v in verdicts if v.status == "found"), key=lambda v: (v.site.rank, v.site.index))
        missing = sum(1 for v in verdicts if v.status == "not found")
        skipped = sum(1 for v in verdicts if v.status == "skipped")
        errors = [v for v in verdicts if v.status == "error"]
        end = start + len(batch)
        lines = [f"{name!r} on sites {start + 1}-{end} of {len(ranked)}" + (f" (tags: {', '.join(wanted)})"
                                                                            if wanted else "")
                 + f": {len(found)} found, {missing} not found, {len(errors)} could not be checked"
                 + (f", {skipped} do not allow such a name" if skipped else "")
                 + (f", {len(late)} not reached within {CALL_SECONDS:g} s" if late else "")]
        if found:
            lines.append("found (a page for this name exists - check that it is the same person):")
            for v in found:
                note = " (the site's search: similar names too)" if v.site.similar else ""
                lines.append(f"  {v.site.name}: {shown(v.url, 200)}  [{', '.join(v.site.tags[:4])}]{note}")
        if errors:
            kinds: dict[str, list[str]] = {}
            for v in errors:
                kinds.setdefault(v.detail.split(":")[0], []).append(v.site.name)
            lines.append("could not be checked (no evidence either way):")
            for kind, names in sorted(kinds.items(), key=lambda item: -len(item[1])):
                lines.append(f"  {shown(kind, 80)} ({len(names)}): {', '.join(names[:12])}"
                             + (" ..." if len(names) > 12 else ""))
        if late:
            lines.append("not reached in time: " + ", ".join(s.name for s in late[:20]) + (" ..." if len(late) > 20
                                                                                          else ""))
        if end < len(ranked):
            lines.append(f"next: search_username with offset={end} checks the next sites")
        return bounded(lines)
    return await answer_async(work)


@mcp.tool(annotations=SEARCH, structured_output=False)
async def check_site(username: str, site: str) -> str:
    """Check a username on one site and say why: the URL asked, the HTTP status, how the site is judged.

    Args:
        username: the name to look for, e.g. "john_doe"
        site: the site's name as list_sites shows it, e.g. "GitHub"
    """
    async def work() -> str:
        name = check_username(username)
        wanted = _text(site, "site", 100, "GitHub")
        entry = database().by_name.get(wanted.lower())
        if entry is None:
            close = [s.name for s in database().sites if wanted.lower() in s.name.lower()][:10]
            raise Refused(f"no site {shown(wanted, 100)!r} in maigret's database"
                          + (f"; similar: {', '.join(close)}" if close else "; list_sites finds it"))
        if entry.why_not:
            raise Refused(f"{entry.name} is not checked by this server: {entry.why_not}")
        async with client() as http:
            verdict = await check(http, entry, name)
        lines = [f"{entry.name}: {verdict.status}" + (f" - {shown(verdict.detail, 200)}" if verdict.detail else ""),
                 f"profile URL: {shown(verdict.url, 300)}"]
        if entry.url_probe:
            lines.append(f"asked: {shown(entry.probe_url(name), 300)}")
        if verdict.http_status is not None:
            lines.append(f"HTTP status: {verdict.http_status}")
        lines.append(f"how it is judged: {entry.check_type}"
                     + (f"; profile marks {entry.presence[:3]}" if entry.presence else "")
                     + (f"; not-found marks {entry.absence[:3]}" if entry.absence else ""))
        if entry.similar:
            lines.append("note: the site's search finds similar names too")
        return bounded([shown(line, 1000) for line in lines])
    return await answer_async(work)


@mcp.tool(annotations=LOCAL, structured_output=False)
def list_sites(tag: str = "", name_filter: str = "", offset: int = 0) -> str:
    """List the sites of maigret's database (most popular first) with their tags and whether this server checks them
    (and why not). Nothing is sent anywhere.

    Args:
        tag: only sites with this tag, e.g. "coding" (list_tags shows them)
        name_filter: only names containing this (any case), e.g. "git"
        offset: skip this many (to see the next ones)
    """
    def work() -> str:
        wanted = check_tags(tag)
        needle = _text(name_filter, "name_filter", 100, "git").lower()
        start = _int(offset, "offset", 0, 100_000)
        sites = sorted((s for s in database().sites
                        if (not wanted or set(wanted) & {t.lower() for t in s.tags}) and needle in s.name.lower()),
                       key=lambda s: (s.rank, s.index))
        if start and start >= len(sites):
            raise Refused(f"offset: there are only {len(sites)} sites")
        part = sites[start:start + MAX_LIST]
        checked = sum(1 for s in sites if not s.why_not)
        lines = [f"{len(sites)} sites in maigret {MAIGRET_VERSION}'s database"
                 + (f" with tag {', '.join(wanted)}" if wanted else "")
                 + (f" matching {needle!r}" if needle else "")
                 + f" ({checked} checked by this server)"
                 + (f", {start + 1}-{start + len(part)} shown" if part else "")]
        for s in part:
            rank = f"#{s.rank}" if s.rank != sys.maxsize else "unranked"
            lines.append(f"{s.name}  {shown(s.url_main or s.url, 80)}  {rank}  [{', '.join(s.tags[:5])}]"
                         + (f"  not checked: {s.why_not}" if s.why_not else ""))
        if start + len(part) < len(sites):
            lines.append(f"(more: offset={start + len(part)})")
        return bounded([shown(line, 400) for line in lines])
    return answer(work)


@mcp.tool(annotations=LOCAL, structured_output=False)
def list_tags() -> str:
    """List the tags of maigret's sites (topics such as coding, gaming, forum, and country codes) with the number of
    sites this server checks for each. Nothing is sent anywhere."""
    def work() -> str:
        db = database()
        counts = {tag: 0 for tag in db.tags}
        for s in db.sites:
            if not s.why_not:
                for tag in s.tags:
                    counts[tag] = counts.get(tag, 0) + 1
        topics = [(t, n) for t, n in counts.items() if len(t) > 2 or not t.isalpha()]
        countries = [(t, n) for t, n in counts.items() if len(t) <= 2 and t.isalpha()]
        lines = [f"{len(db.checkable([]))} of {len(db.sites)} sites are checked by this server",
                 "topics: " + ", ".join(f"{t} ({n})" for t, n in sorted(topics)),
                 "countries: " + ", ".join(f"{t} ({n})" for t, n in sorted(countries))]
        return bounded(lines)
    return answer(work)


